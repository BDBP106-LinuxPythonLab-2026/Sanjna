#Mathematical operations between k and n
k= int(input("Enter an integer k: "))
n= int(input("Enter a positive integer n: "))

print("Doing mathematical operations between "+str(k)+" and "+str(n)+" :")
print("Addition: "+str(k+n)+" ")
print("Subtraction: "+str(k-n)+" ")
print("Multiplication: "+str(k*n)+" ")
print("Division: "+str(k/n)+" ")
print("Exponentiation: "+str(k**n)+" ")
print("Modulo: "+str(k%n)+" ")
